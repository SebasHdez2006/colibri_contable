    /**
     * Test 1: Desktop summary (resumenEstados) must agree with the formal
     * financial statements generated by the same service.
     *
     * resumenEstados() aggregates balanza() which only covers PERIOD movements
     * (fecha_contable BETWEEN desde AND hasta). estadoSituacion() uses cumulative
     * balances up to the cut date. For stock figures (activos/pasivos/patrimonio)
     * these MUST be equal; a divergence means the dashboard reports different
     * numbers than the official statements — a parity violation.
     */
    @Test
    @EnabledIf("dbDisponible")
    @DisplayName("Counterexample 1: resumenEstados diverges from estadoSituacion")
    void testResumenVsEstadoSituacion() {
        System.out.println("\n=== TEST 1: resumenEstados vs estadoSituacion ===");

        List<LibroContableService.LineaEstado> situacion =
                context.libros().estadoSituacion(HASTA);
        LibroContableService.LineaEstado totalActivos = buscarLinea(situacion, "TOTAL ACTIVOS");
        LibroContableService.LineaEstado totalPasPat =
                buscarLinea(situacion, "TOTAL PASIVOS Y PATRIMONIO");
        Map<String, BigDecimal> resumen = context.libros().resumenEstados(DESDE, HASTA);

        BigDecimal activosEstado = totalActivos != null ? totalActivos.importe() : BigDecimal.ZERO;
        BigDecimal pasPatEstado = totalPasPat != null ? totalPasPat.importe() : BigDecimal.ZERO;
        BigDecimal activosResumen = resumen.getOrDefault("activos", BigDecimal.ZERO);
        BigDecimal pasPatResumen = resumen.getOrDefault("pasivoPatrimonio", BigDecimal.ZERO);

        System.out.printf("estadoSituacion TOTAL ACTIVOS:             %,.2f%n", activosEstado);
        System.out.printf("resumenEstados   'activos':               %,.2f%n", activosResumen);
        System.out.printf("estadoSituacion TOTAL PASIVOS+PATRIMONIO:  %,.2f%n", pasPatEstado);
        System.out.printf("resumenEstados   'pasivoPatrimonio':      %,.2f%n", pasPatResumen);

        BigDecimal diffActivos = activosEstado.subtract(activosResumen).abs();
        BigDecimal diffPasPat = pasPatEstado.subtract(pasPatResumen).abs();
        System.out.printf("Diff activos: %s   Diff pasivo+patrimonio: %s%n", diffActivos, diffPasPat);

        // WILL FAIL if resumenEstados uses period-only movements for stock figures.
        assertTrue(diffActivos.compareTo(TOLERANCIA) <= 0
                        && diffPasPat.compareTo(TOLERANCIA) <= 0,
                "PARITY BUG: resumenEstados (dashboard) diverges from estadoSituacion. " +
                "activos diff=" + diffActivos + ", pasivoPatrimonio diff=" + diffPasPat +
                ". Unificar cálculos en ReportCalculationService lo corregirá.");
    }

