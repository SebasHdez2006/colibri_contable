    @DisplayName("Counterexample 2: Accounting equation inside estadoSituacion")
    void testAccountingEquationEnEstado() {
        System.out.println("\n=== TEST 2: Ecuación contable en estadoSituacion ===");

        List<LibroContableService.LineaEstado> lineas =
                context.libros().estadoSituacion(HASTA);

        LibroContableService.LineaEstado diferencia = lineas.stream()
                .filter(l -> "DIFERENCIA DE BALANCE".equals(l.concepto()))
                .findFirst().orElse(null);

        assertNotNull(diferencia, "estadoSituacion debe reportar DIFERENCIA DE BALANCE");
        System.out.printf("DIFERENCIA DE BALANCE: %,.4f%n", diferencia.importe());

        // WILL FAIL if rounding/aggregation errors break the equation.
        assertTrue(diferencia.importe().abs().compareTo(TOLERANCIA) <= 0,
                "CHAIN BUG: Activo != Pasivo + Patrimonio, diferencia=" +
                diferencia.importe() + ". FinancialStatementValidator lo hará cumplir.");
    }

    /**
     * Test 3: Excel export round-trip preserves monetary values.
     *
     * Replicates ReportesView.balanza path exactly:
     *   headers "Código","Cuenta","Debe (USD)","Haber (USD)"
     *   rows from balanza() with toPlainString()
     *   agregarTotal equivalent (BigDecimal sums) as last row
     *   ReportService.exportarExcel -> POI cells -> parse -> compare.
     */
    @Test
    @EnabledIf("dbDisponible")
    @DisplayName("Counterexample 3: Excel export loses monetary precision")
    void testExcelExportRoundTrip() throws Exception {
        System.out.println("\n=== TEST 3: Excel export round-trip (ruta real UI) ===");

        List<LibroContableService.LineaMayor> balanza = context.libros().balanza(DESDE, HASTA);
        assertFalse(balanza.isEmpty(), "La balanza no puede estar vacía");

        // Same headers/rows as ReportesView for BALANZA.
        List<String> encabezados = List.of("Código", "Cuenta", "Debe (USD)", "Haber (USD)");
        List<List<String>> filas = new ArrayList<>();
        BigDecimal totalDebe = BigDecimal.ZERO;
        BigDecimal totalHaber = BigDecimal.ZERO;
        for (LibroContableService.LineaMayor l : balanza) {
            filas.add(List.of(l.cuenta(), l.nombre(),
                    l.debe().toPlainString(), l.haber().toPlainString()));
            totalDebe = totalDebe.add(l.debe());
            totalHaber = totalHaber.add(l.haber());
        }
        // TOTALES row like agregarTotal (columns 2..3)
        List<String> total = new ArrayList<>(List.of("TOTALES", "", "", ""));
        total.set(2, totalDebe.toPlainString());
        total.set(3, totalHaber.toPlainString());
        filas.add(total);

        byte[] xlsx = context.reports().exportarExcel(
                "Balanza de Comprobación", "01/01/2026 - 31/01/2026",
                encabezados, filas);

        try (Workbook wb = new XSSFWorkbook(new ByteArrayInputStream(xlsx))) {
            var sheet = wb.getSheetAt(0);
            // Locate header row by "Debe (USD)" in cell 2.
            int headerRow = -1;
            for (int r = 0; r <= sheet.getLastRowNum(); r++) {
                var row = sheet.getRow(r);
                if (row != null && row.getCell(2) != null
                        && "Debe (USD)".equals(row.getCell(2).getStringCellValue())) {
                    headerRow = r;
                    break;
                }
            }
            assertTrue(headerRow >= 0, "No se encontró encabezado 'Debe (USD)' en el XLSX");

            int dataRow = headerRow + 1;
            int comparadas = 0;
            BigDecimal maxDiff = BigDecimal.ZERO;
            for (LibroContableService.LineaMayor l : balanza) {
                var row = sheet.getRow(dataRow++);
                assertNotNull(row, "Falta fila para cuenta " + l.cuenta());
                assertEquals(l.cuenta(), row.getCell(0).getStringCellValue());
                BigDecimal[] expected = {l.debe(), l.haber()};
                for (int col = 2; col <= 3; col++) {
                    var cell = row.getCell(col);
                    assertNotNull(cell, "Celda vacía en " + l.cuenta() + " col " + col);
                    BigDecimal actual = BigDecimal.valueOf(cell.getNumericCellValue());
                    BigDecimal diff = expected[col - 2].subtract(actual).abs();
                    maxDiff = diff.max(maxDiff);
                    comparadas++;
                }
            }
            // Verify TOTALES row matches BigDecimal sums.
            var totalRow = sheet.getRow(dataRow);
            assertNotNull(totalRow, "Falta fila TOTALES");
            BigDecimal totalDebeXlsx = BigDecimal.valueOf(totalRow.getCell(2).getNumericCellValue());
            BigDecimal totalHaberXlsx = BigDecimal.valueOf(totalRow.getCell(3).getNumericCellValue());
            BigDecimal diffTD = totalDebe.subtract(totalDebeXlsx).abs();
            BigDecimal diffTH = totalHaber.subtract(totalHaberXlsx).abs();
            maxDiff = maxDiff.max(diffTD).max(diffTH);

            System.out.printf("Celdas comparadas: %d (+2 totales)   Max diff: %s%n",
                    comparadas, maxDiff);
            System.out.printf("TOTALES: desktop debe=%s haber=%s | xlsx debe=%s haber=%s%n",
                    totalDebe, totalHaber, totalDebeXlsx, totalHaberXlsx);

            // WILL FAIL if doubleValue() round-trip or column detection loses precision.
            assertTrue(maxDiff.compareTo(TOLERANCIA) <= 0,
                    "PARITY BUG: Excel diverges from desktop values. maxDiff=" + maxDiff +
                    " en " + comparadas + " celdas. exportarExcel usa doubleValue() " +
                    "y esColumnaMonetaria no reconoce todas las columnas.");
        }
    }

    /**
     * Test 4: estadoResultados internal consistency — full reconciliation chain.
     *
     * utilidadNeta = ventasNetas - costos - gastosOp + resultadoFinanciero
     *              + otrosResultados - (impuestoCorriente + impuestoDiferidoNeto)
     *
     * Mirrors construirEstadoResultados() exactly; any deviation > $0.01 is a
     * chain bug that FinancialStatementValidator must catch.
     */
    @Test
    @EnabledIf("dbDisponible")
    @DisplayName("Counterexample 4: estadoResultados internal reconciliation")
    void testEstadoResultadosReconciliation() {
        System.out.println("\n=== TEST 4: Reconciliación interna estadoResultados ===");

        List<LibroContableService.LineaEstado> lineas =
                context.libros().estadoResultados(DESDE, HASTA);

        BigDecimal ventasNetas = monto(lineas, "VENTAS NETAS");
        BigDecimal costos = monto(lineas, "COSTO DE VENTAS");
        BigDecimal gastosOp = monto(lineas, "TOTAL GASTOS DE OPERACIÓN");
        BigDecimal resultadoFin = monto(lineas, "RESULTADO FINANCIERO NETO");
        BigDecimal otrosRes = monto(lineas, "Otros ingresos (gastos) netos");
        BigDecimal impCorriente = monto(lineas, "Impuesto corriente");
        BigDecimal impDiferido = monto(lineas, "Impuesto diferido neto");
        BigDecimal utilidadNeta = monto(lineas, "UTILIDAD (PÉRDIDA) NETA DEL PERÍODO");

        BigDecimal esperado = ventasNetas.subtract(costos).subtract(gastosOp)
                .add(resultadoFin).add(otrosRes)
                .subtract(impCorriente).subtract(impDiferido);
        BigDecimal diff = esperado.subtract(utilidadNeta).abs();

        System.out.printf("VentasNetas: %,.2f  Costos: %,.2f  GastosOp: %,.2f%n",
                ventasNetas, costos, gastosOp);
        System.out.printf("ResFinanciero: %,.2f  OtrosRes: %,.2f  ImpCorr: %,.2f  ImpDif: %,.2f%n",
                resultadoFin, otrosRes, impCorriente, impDiferido);
        System.out.printf("Esperado: %,.2f   UtilidadNeta: %,.2f   Diferencia: %s%n",
                esperado, utilidadNeta, diff);

        assertTrue(diff.compareTo(TOLERANCIA) <= 0,
                "CHAIN BUG: cadena de estado de resultados no reconcilia. diff=" + diff +
                ". FinancialStatementValidator lo detectará.");
    }

    private static LibroContableService.LineaEstado buscarLinea(
            List<LibroContableService.LineaEstado> lineas, String concepto) {
        return lineas.stream()
                .filter(l -> concepto.equals(l.concepto()))
                .findFirst().orElse(null);
    }

    private static BigDecimal monto(List<LibroContableService.LineaEstado> lineas, String concepto) {
        LibroContableService.LineaEstado l = buscarLinea(lineas, concepto);
        return l != null ? l.importe() : BigDecimal.ZERO;
    }

